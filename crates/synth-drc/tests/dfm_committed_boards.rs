//! The DFM rules run on boards that are committed to the repository.
//!
//! These pin what a fab-style check finds on real boards, so a rule change that
//! moves a count shows up here and is reviewed. They also document the
//! blast radius of `--dfm-gate`: the boards below would be blocked on a
//! release export if the gate were on.

use std::collections::BTreeMap;
use std::path::PathBuf;

use synth_drc::dfm::{check_dfm, DfmSeverity};
use synth_drc::ManufacturerProfile;

fn counts_for(relative: &str) -> (BTreeMap<String, usize>, usize) {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join(relative);
    let text = std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    let report = check_dfm(&text, &ManufacturerProfile::jlc_standard()).expect("board parses");
    let counts = report
        .counts()
        .into_iter()
        .map(|((rule, severity), n)| {
            let severity = match severity {
                DfmSeverity::Danger => "danger",
                DfmSeverity::Warning => "warning",
            };
            (format!("{rule} {severity}"), n)
        })
        .collect();
    (counts, report.unchecked_silk_text)
}

#[test]
fn rp2350_example_findings_are_pinned() {
    let (counts, unmeasured_text) =
        counts_for("examples/rp2350/rp2350_devboard_freerouting_clean.kicad_pcb");
    let expected: BTreeMap<String, usize> = [
        ("pad_to_pad warning", 3),
        // Via barrels are plated holes too; before they were measured this was 0.
        ("pth_to_trace warning", 22),
        ("silk_line_width warning", 173),
        ("silk_to_hole danger", 5),
        ("silk_to_pad danger", 64),
    ]
    .into_iter()
    .map(|(k, n)| (k.to_string(), n))
    .collect();
    assert_eq!(counts, expected, "update with the reason a rule moved");
    assert_eq!(
        unmeasured_text, 59,
        "silk text items are counted, not measured"
    );
}

/// The buck board is regenerated by qualification work, so its exact counts
/// are not pinned. What must hold: the gate would block it today (silk on a
/// pad), and no pad-spacing Danger exists on a routed board.
#[test]
fn buck_example_would_be_blocked_only_by_silk_rules() {
    let (counts, _) = counts_for("qualification/class-b/buck/kicad/buck.kicad_pcb");
    let danger_rules: Vec<&str> = counts
        .keys()
        .filter(|k| k.ends_with(" danger"))
        .map(String::as_str)
        .collect();
    assert!(
        !danger_rules.is_empty(),
        "the buck board is expected to be blocked by --dfm-gate"
    );
    assert!(
        danger_rules
            .iter()
            .all(|r| *r == "silk_to_pad danger" || *r == "silk_to_hole danger"),
        "only silk rules should grade Danger on the buck board: {danger_rules:?}"
    );
}
